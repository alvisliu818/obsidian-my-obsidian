/**
 * One bundle for four plugins.
 *
 * The externals / plugins / defines below are the union of what each module's
 * own esbuild config needed. They do not collide: the @codemirror/* and
 * @lezer/* externals are shared by logseq, jupyter and breadcrumb (all want
 * Obsidian's own CM instance), and the `cm-bundle:` namespace is used by both
 * logseq and jupyter for their private CodeMirror copy.
 */
import esbuild from "esbuild";
import esbuildSvelte from "esbuild-svelte";
import { sveltePreprocess } from "svelte-preprocess";
import process from "process";
import builtins from "builtin-modules";
import { createRequire } from "node:module";
import { readFileSync, globSync as fsGlobSync } from "node:fs";
import { readFile } from "node:fs/promises";
import path from "node:path";

const nodeRequire = createRequire(import.meta.url);
const prod = process.argv[2] === "production";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

// ---------------------------------------------------------------------------
// logseq: compiled SQLite + the Oniguruma regex engine, embedded as base64.
//
// Both ship as separate .wasm files. A plugin has no reliable URL to fetch
// them from, and a missing sidecar would silently kill the SQLite index or the
// TextMate highlighting — so they travel inside main.js instead.
// ---------------------------------------------------------------------------
const waSqliteDir = path.dirname(nodeRequire.resolve("wa-sqlite/package.json"));
const WA_SQLITE_WASM_B64 = readFileSync(
  path.join(waSqliteDir, "dist", "wa-sqlite.wasm"),
).toString("base64");
const onigDir = path.dirname(nodeRequire.resolve("vscode-oniguruma/package.json"));
const ONIG_WASM_B64 = readFileSync(path.join(onigDir, "release", "onig.wasm")).toString(
  "base64",
);

// ---------------------------------------------------------------------------
// browser: scripts that must run INSIDE the webview guest.
//
// They have to see the live page DOM, so they travel as source text, not as
// imports (a module import would run in the plugin's realm and see no
// document). Bundled to IIFE strings at build time and inlined.
// ---------------------------------------------------------------------------
const BROWSER = "modules/browser";
async function bundleVendorSource(entry) {
  const r = await esbuild.build({
    entryPoints: [entry],
    bundle: true,
    format: "iife",
    target: "es2020",
    write: false,
    minify: prod,
    legalComments: "none",
    logLevel: "silent",
  });
  return r.outputFiles[0].text;
}
const READABILITY_SOURCE = await bundleVendorSource(
  `${BROWSER}/src/vendor/readability-entry.ts`,
);
const CLIP_SOURCE = await bundleVendorSource(`${BROWSER}/src/browser/clipScript.ts`);
const PRELOAD_SOURCE = await bundleVendorSource(`${BROWSER}/src/browser/preload.ts`);
const EXT_PRELOAD_SOURCE = await bundleVendorSource(
  `${BROWSER}/src/extensions/extPreload.ts`,
);

// ---------------------------------------------------------------------------
// audio-recorder: the encoding WebWorker, bundled to an IIFE string.
//
// The plugin starts it via a Blob URL (workers can't be loaded from app://),
// so like the browser scripts above it travels as source text inside the
// bundle. Captured once at build time; editing
// modules/audio-recorder/src/audio/encodingWorker.ts requires a rebuild.
// ---------------------------------------------------------------------------
const ENCODING_WORKER_SOURCE = await bundleVendorSource(
  "modules/audio-recorder/src/audio/encodingWorker.ts",
);

// ---------------------------------------------------------------------------
// logseq + jupyter: a PRIVATE CodeMirror copy for the code-block editor.
//
// `cm-bundle:` imports get their own bundled CM. Everything reachable from
// such an import (including @codemirror/* pulled in transitively) is bundled
// into the same copy so facets/tags stay a single instance. Resolution runs
// through a dedicated namespace because the external list is matched on the
// raw specifier.
// ---------------------------------------------------------------------------
const cmBundlePlugin = {
  name: "cm-bundle",
  setup(build) {
    const CM_RE = /^cm-bundle:(.+)$/;
    const EXTERNAL_CM_RE = /^@(codemirror|lezer)\//;
    build.onResolve({ filter: /./ }, (args) => {
      const m = CM_RE.exec(args.path);
      const spec = m ? m[1] : null;
      const isNested = args.namespace === "cm-bundle" && EXTERNAL_CM_RE.test(args.path);
      if (!spec && !isNested) return null;
      return { path: nodeRequire.resolve(spec ?? args.path), namespace: "cm-bundle" };
    });
    build.onLoad({ filter: /./, namespace: "cm-bundle" }, (args) => ({
      contents: readFileSync(args.path, "utf8"),
      loader: path.extname(args.path) === ".ts" ? "ts" : "js",
      resolveDir: path.dirname(args.path),
    }));
  },
};

// ---------------------------------------------------------------------------
// omnisearch: Svelte 5 components for its search modals.
//
// esbuild-svelte self-scopes to `\.svelte$` files, so it is inert for the
// other modules; Svelte 5's `mount`/`unmount` runtime comes in through
// node_modules and bundles alongside. `css: injected` matches the upstream
// config (styles end up inline in the DOM rather than a separate css file).
//
// momentum 的 .svelte 不归这个插件管——见下面 momentumSveltePlugin（Svelte 4）。
// ---------------------------------------------------------------------------
const sveltePlugin = esbuildSvelte({
  compilerOptions: { css: "injected", dev: !prod },
  // obsidian-git 的组件带大量 a11y 提示，上游也是这么过滤的
  filterWarnings: (warning) => !warning.code.startsWith("a11y-"),
  preprocess: sveltePreprocess(),
});

// ---------------------------------------------------------------------------
// momentum（含并入的 WorkLife Calendar）: Svelte 4 组件。
//
// 为什么是 4 而不是根仓的 5：WorkLife 的视图用 Svelte 3 的
// `new Component({ target, props })` 实例化（配 $destroy/$set），且
// ui/Calendar.svelte 把 obsidian-calendar-ui 的预编译 Svelte 3 class 当子组件
// 用。Svelte 4 与 Svelte 3 的 class 组件 API、`new Child({...})` 子组件约定
// 一致；Svelte 5 默认编译成函数组件，两条路都炸（前者 `$.prop()` 内部
// `Symbol($state) in undefined`，后者 "Class constructor cannot be invoked
// without 'new'"；componentApi:4 兼容模式只包根组件，子组件仍是函数约定）。
//
// 实现：modules/momentum/node_modules 下嵌套装着 svelte@4 + esbuild-svelte
// （该模块自包含依赖，与独立项目 obsidian-momentum 一致；根 node_modules 的
// svelte@5 供 omnisearch/obsidian-git 使用）。用 createRequire 从模块目录
// 解析出这份 esbuild-svelte——它 require("svelte/compiler") 时自然落到嵌套
// 的 svelte@4。include 只罩 momentum 下的 .svelte，且必须注册在根
// sveltePlugin 之前（onLoad 按插件顺序先到先得）。
//
// verbatimModuleSyntax 同样只经 options 传（不动 tsconfig）：没有它
// ts.transpileModule 会把「只被 $store 引用」的 import 当未使用删掉，
// Svelte 编译器随即报 `global_reference_invalid`。
// ---------------------------------------------------------------------------
const momentumRequire = createRequire(path.resolve("modules/momentum/package.json"));
const esbuildSvelte4 = momentumRequire("esbuild-svelte");
const momentumSveltePlugin = esbuildSvelte4({
  include: /momentum.*\.svelte$/,
  compilerOptions: { css: "injected", dev: !prod },
  filterWarnings: (warning) => !warning.code.startsWith("a11y-"),
  preprocess: sveltePreprocess({
    typescript: { compilerOptions: { verbatimModuleSyntax: true } },
  }),
});

// ---------------------------------------------------------------------------
// omnisearch: dexie 的 dual-package-hazard 补丁。
//
// 上游用 pnpm patch 打（modules/omnisearch/patches/dexie.patch）：去掉
// dexie import-wrapper 里的 Symbol.for("Dexie") 全局实例检查。pnpm 的补丁
// 格式与 patch-package 不兼容（试过），所以改为 esbuild onLoad 插件在打包
// 时直接替换——不依赖 node_modules 的状态，构建自愈。
//
// 原代码（两个 import-wrapper*.mjs 都有）：
//   const DexieSymbol = Symbol.for("Dexie");
//   const Dexie = globalThis[DexieSymbol] || (globalThis[DexieSymbol] = _Dexie);
//   if (_Dexie.semVer !== Dexie.semVer) { throw ... }
// 单文件打包后只存在一份 dexie，这段检查没有意义且占地方。
// ---------------------------------------------------------------------------
const dexiePatchPlugin = {
	name: "dexie-patch",
	setup(build) {
		build.onLoad({ filter: /dexie[\\/]import-wrapper(-prod)?\.mjs$/ }, (args) => {
			let contents = readFileSync(args.path, "utf8");
			contents = contents.replace(
				/const DexieSymbol = Symbol\.for\("Dexie"\);[\s\S]*?_Dexie\.semVer\);\s*\n\}/,
				"const Dexie = _Dexie;",
			);
			return { contents, loader: "js", resolveDir: path.dirname(args.path) };
		});
	},
};

// ---------------------------------------------------------------------------
// open-tab-settings: `glob:./locales/*.json` 聚合导入（上游 esbuild 插件原样
// 移植）。编译期把 glob 匹配到的 JSON 各自 import 后聚成一个对象，键取文件名。
// TS 侧由 modules/open-tab-settings/src/glob.d.ts 的 `declare module 'glob:*'`
// 兜住类型。
// ---------------------------------------------------------------------------
const importGlobPlugin = {
  name: "import-glob",
  setup(build) {
    build.onResolve({ filter: /^glob:.*$/ }, async (args) => ({
      path: args.path.replace(/^glob:/, ""),
      namespace: "import-glob",
      pluginData: { resolveDir: args.resolveDir },
    }));
    build.onLoad({ filter: /.*/, namespace: "import-glob" }, async (args) => {
      const files = fsGlobSync(args.path, { cwd: args.pluginData.resolveDir })
        .map((f) => f.split(path.sep).join("/"))
        .sort();
      return {
        contents: [
          ...files.map((module, i) => `import m${i} from './${module}'`),
          "export default {",
          ...files.map((f, i) => `${JSON.stringify(path.basename(f, path.extname(f)))}: m${i},`),
          "}",
        ].join("\n"),
        resolveDir: args.pluginData.resolveDir,
      };
    });
  },
};

// ---------------------------------------------------------------------------
// music-player: buffer/events/process/string_decoder 打包而非 external。
//
// 上游 esbuild 配置特意把这四个（含 node: 前缀写法）从 builtin external 里
// 摘出来打进 bundle，让 music-metadata 这类库的 require('process/')、
// require('buffer') 在移动端（无 nodeIntegration）也能工作。聚合的 external
// 列表是全局的，罩不到模块粒度 —— 所以用 onResolve 按 importer 路径覆盖：
// 只对 modules/music-player/ 下的导入返回 npm shim 包的真实路径（进 bundle），
// 其余 importer 返回 undefined 走默认解析（维持 external 语义不变）。
// ---------------------------------------------------------------------------
const musicPlayerRequire = createRequire(
  path.resolve("modules/music-player/package.json"),
);
const NODE_SHIM_RE = /^(node:)?(buffer|events|process|string_decoder)$/;
const musicPlayerShimsPlugin = {
  name: "music-player-node-shims",
  setup(build) {
    build.onResolve({ filter: NODE_SHIM_RE }, (args) => {
      if (!args.importer.split(path.sep).join("/").startsWith("modules/music-player/"))
        return undefined;
      try {
        return { path: musicPlayerRequire.resolve(args.path.replace(/^node:/, "")) };
      } catch {
        return undefined; // 解析不到就交回默认流程（external），构建期会再报错定位
      }
    });
  },
};

// ---------------------------------------------------------------------------
// media-extended: 上游 esbuild 配置三个插件的移植（运行时语义不变）。
//
// ① inline:* —— webview 预载脚本/油猴脚本在构建期打成 CJS 字符串内联。
//    external 集合与上游一致；minify 上游硬编码 true。
// ② media-captions 补丁 —— 上游把该包源码里的 ` instanceof HTMLElement `
//    替换为 arktype 的 `.instanceOf(HTMLElement)`，不套用会运行时报错。
//    上游 filter 用正斜杠，Windows 路径是反斜杠，此处两种都匹配。
// ③ NODE_ENV 作用域替换 —— 上游用 define，但聚合的 define 是全局的，会连带
//    改 omnisearch 等模块的运行时分支；改为只对 modules/media-extended/ 下
//    （含其 node_modules 里的 react/vidstack）文件做文本替换。
// ---------------------------------------------------------------------------
const mxInlinePlugin = {
  name: "mx-inline-code",
  setup(build) {
    build.onResolve({ filter: /^inline:/ }, (args) => ({
      path: path.resolve(args.resolveDir, args.path.replace(/^inline:/, "")),
      namespace: "mx-inline",
    }));
    build.onLoad({ filter: /.*/, namespace: "mx-inline" }, async (args) => {
      const r = await esbuild.build({
        entryPoints: [args.path],
        write: false,
        bundle: true,
        minify: true,
        format: "cjs",
        target: "es2022",
        external: ["media-extended", "fs/promises", "electron", "path"],
        ...(prod ? { drop: ["console"] } : {}),
        logLevel: "silent",
      });
      return { contents: r.outputFiles[0].text, loader: "text" };
    });
  },
};
const mxCaptionsPlugin = {
  name: "mx-fix-media-captions",
  setup(build) {
    build.onLoad({ filter: /media-captions[\\/]/ }, async (args) => {
      const code = await readFile(args.path, "utf8");
      return {
        contents: code.replaceAll(/\b instanceof HTMLElement\b/g, ".instanceOf(HTMLElement)"),
        loader: "js",
        resolveDir: path.dirname(args.path),
      };
    });
  },
};
const mxNodeEnvPlugin = {
  name: "mx-node-env",
  setup(build) {
    build.onLoad({ filter: /media-extended[\\/]/ }, async (args) => {
      const contents = await readFile(args.path, "utf8");
      if (!contents.includes("process.env.NODE_ENV")) return undefined;
      const ext = path.extname(args.path);
      return {
        contents: contents.replaceAll(
          "process.env.NODE_ENV",
          JSON.stringify(prod ? "production" : "development"),
        ),
        loader: ext === ".tsx" ? "tsx" : ext === ".ts" ? "ts" : "js",
        resolveDir: path.dirname(args.path),
      };
    });
  },
};

const context = await esbuild.context({
  banner: { js: banner },
  entryPoints: ["src/main.ts"],
  bundle: true,
  // obsidian = the host API; @codemirror/* + @lezer/* = Obsidian's own CM6
  // instance (official plugin convention), so every editor here shares ONE
  // CodeMirror with the native editor and with community plugins.
  external: [
    "obsidian",
    "electron",
    "@codemirror/state",
    "@codemirror/view",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/autocomplete",
    "@codemirror/search",
    "@codemirror/lint",
    "@codemirror/collab",
    "@lezer/common",
    "@lezer/highlight",
    "@lezer/lr",
    ...builtins,
    // ollama 等包用 `node:fs` 带前缀的写法，裸名列表罩不住
    ...builtins.map((m) => `node:${m}`),
  ],
  plugins: [cmBundlePlugin, momentumSveltePlugin, sveltePlugin, dexiePatchPlugin, importGlobPlugin, musicPlayerShimsPlugin, mxInlinePlugin, mxCaptionsPlugin, mxNodeEnvPlugin],
  // Monaco 的 codicon.css 引用 .ttf 字体(图标字形)。内联成 dataurl:图标
  // 只有几 KB,而少这一条整个构建会以 "No loader is configured for .ttf" 失败。
  // (与独立插件 obsidian-logseq 的 esbuild.mjs 同款配置。)
  loader: {
    ".ttf": "dataurl",
    ".woff": "dataurl",
    ".woff2": "dataurl",
    // music-player: React 组件入口（tsx）+ 组件内 css import（样式统一走根
    // styles.css 的 Music Player 分段，JS 侧按上游同款空模块处理，不产 main.css）
    ".tsx": "tsx",
    ".css": "empty",
    ".less": "empty",
    // media-extended: svg/ejs 按上游以文本内联
    ".svg": "text",
    ".ejs": "text",
  },
  define: {
    // wa-sqlite's Emscripten glue reads import.meta.url to locate its wasm;
    // in the CJS bundle that is `{}`, which throws before it ever looks at
    // `wasmBinary`. Empty string == "no script dir", which is what we want.
    "import.meta.url": '""',
    __WA_SQLITE_WASM_B64__: JSON.stringify(WA_SQLITE_WASM_B64),
    __ONIG_WASM_B64__: JSON.stringify(ONIG_WASM_B64),
    __READABILITY_SOURCE__: JSON.stringify(READABILITY_SOURCE),
    __CLIP_SOURCE__: JSON.stringify(CLIP_SOURCE),
    __PRELOAD_SOURCE__: JSON.stringify(PRELOAD_SOURCE),
    __EXT_PRELOAD_SOURCE__: JSON.stringify(EXT_PRELOAD_SOURCE),
    __ENCODING_WORKER_SOURCE__: JSON.stringify(ENCODING_WORKER_SOURCE),
    __ADBLOCK_RULES__: JSON.stringify(
      readFileSync(`${BROWSER}/src/assets/adblock-rules.txt`, "utf8"),
    ),
  },
  format: "cjs",
  target: "es2021",
  // esm-env（obsidian-git 的 svelte 组件用它）按这个条件切换 dev/prod 分支
  conditions: [prod ? "production" : "development"],
  // isomorphic-git 在移动端需要 Buffer 全局（obsidian-git 上游的 polyfill）
  inject: ["modules/obsidian-git/polyfill_buffer.js"],
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  outfile: "main.js",
  minify: prod,
});

if (prod) {
  await context.rebuild();
  process.exit(0);
} else {
  await context.watch();
}
