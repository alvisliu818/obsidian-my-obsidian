import esbuild from "esbuild";
import process from "process";
import builtins from "builtin-modules";
import { readFileSync } from "node:fs";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === "production";

/**
 * The clipper runs Readability INSIDE the page (webview guest) — it has to see
 * the live DOM, so the library must travel as source text, not as an import
 * (a module import would run in the plugin's realm and see no document).
 *
 * Same trick as the SiYuan plugin: bundle the vendor entry to an IIFE string at
 * build time and inline it. One file to deploy, nothing to fetch at runtime.
 */
async function bundleVendorSource(entry) {
  const r = await esbuild.build({
    entryPoints: [entry],
    bundle: true,
    format: "iife",
    target: "es2020",
    write: false,
    minify: prod,
    legalComments: "none",
    logLevel: "silent",
  });
  return r.outputFiles[0].text;
}

const READABILITY_SOURCE = await bundleVendorSource("src/vendor/readability-entry.ts");
// The in-page collector: selection/Readability extraction + image URL harvest.
const CLIP_SOURCE = await bundleVendorSource("src/browser/clipScript.ts");
// Runs inside the webview guest as `preload` — needs its own realm, so it is
// written to disk by the plugin on first load (see preload.ts).
const PRELOAD_SOURCE = await bundleVendorSource("src/browser/preload.ts");
// Same idea for extension popups: a file:// guest needs the chrome.* shim.
const EXT_PRELOAD_SOURCE = await bundleVendorSource("src/extensions/extPreload.ts");

const context = await esbuild.context({
  banner: { js: banner },
  entryPoints: ["src/main.ts"],
  bundle: true,
  external: [
    "obsidian",
    "electron",
    ...builtins,
  ],
  define: {
    __READABILITY_SOURCE__: JSON.stringify(READABILITY_SOURCE),
    __CLIP_SOURCE__: JSON.stringify(CLIP_SOURCE),
    __PRELOAD_SOURCE__: JSON.stringify(PRELOAD_SOURCE),
    __EXT_PRELOAD_SOURCE__: JSON.stringify(EXT_PRELOAD_SOURCE),
    __ADBLOCK_RULES__: JSON.stringify(
      readFileSync(new URL("./src/assets/adblock-rules.txt", import.meta.url), "utf8"),
    ),
  },
  format: "cjs",
  target: "es2020",
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  outfile: "main.js",
  minify: prod,
});

if (prod) {
  await context.rebuild();
  process.exit(0);
} else {
  await context.watch();
}
