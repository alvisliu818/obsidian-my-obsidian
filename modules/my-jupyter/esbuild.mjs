import esbuild from "esbuild";
import process from "process";
import builtins from "builtin-modules";
import { createRequire } from "node:module";
import { copyFileSync } from "node:fs";
import path from "node:path";

const nodeRequire = createRequire(import.meta.url);

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === "production";

/**
 * `cm-bundle:` imports get their OWN bundled CodeMirror copy — same strategy as
 * obsidian-logseq's code editor. The notebook's per-cell editors (and their
 * StreamLanguage parsers) must not depend on Obsidian's shared CM instance,
 * where StreamLanguage highlighting silently no-ops (0 spans).
 *
 * Everything reachable from such an import — @codemirror/* and @lezer/* pulled
 * in transitively — is bundled into the same copy so facets/tags stay one
 * instance. Resolution runs through a dedicated namespace because the external
 * list is matched on the raw specifier.
 */
const cmBundlePlugin = {
  name: "cm-bundle",
  setup(build) {
    const CM_RE = /^cm-bundle:(.+)$/;
    const EXTERNAL_CM_RE = /^@(codemirror|lezer)\//;
    build.onResolve({ filter: /./ }, (args) => {
      const m = CM_RE.exec(args.path);
      const spec = m ? m[1] : null;
      const isNested = args.namespace === "cm-bundle" && EXTERNAL_CM_RE.test(args.path);
      if (!spec && !isNested) return null;
      return { path: nodeRequire.resolve(spec ?? args.path), namespace: "cm-bundle" };
    });
    build.onLoad({ filter: /./, namespace: "cm-bundle" }, (args) => ({
      contents: readFileSyncOf(args.path),
      loader: path.extname(args.path) === ".ts" ? "ts" : "js",
      resolveDir: path.dirname(args.path),
    }));
  },
};

function readFileSyncOf(p) {
  // eslint-disable-next-line @typescript-eslint/no-var-requires
  return nodeRequire("fs").readFileSync(p, "utf8");
}

const context = await esbuild.context({
  banner: { js: banner },
  entryPoints: ["src/main.ts"],
  bundle: true,
  // @codemirror/* and @lezer/* are EXTERNAL by the official plugin convention,
  // EXCEPT for what arrives via cm-bundle: imports (handled above, bundled).
  external: [
    "obsidian",
    "electron",
    "@codemirror/state",
    "@codemirror/view",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/autocomplete",
    "@codemirror/search",
    "@codemirror/lint",
    "@codemirror/collab",
    "@lezer/common",
    "@lezer/highlight",
    "@lezer/lr",
    ...builtins,
  ],
  plugins: [cmBundlePlugin],
  format: "cjs",
  target: "es2020",
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  outfile: "main.js",
  minify: prod,
});

// syfe-kernel.py:内置 Python 内核本体(运行时由 kernel/legacyPython 以子进程拉起)。
// 构建产物目录必须带这份脚本,否则内核启动直接报「找不到内核脚本」。
copyFileSync(
  path.join(process.cwd(), "tools", "syfe-kernel.py"),
  path.join(process.cwd(), "syfe-kernel.py"),
);

if (prod) {
  await context.rebuild();
  process.exit(0);
} else {
  await context.watch();
}
