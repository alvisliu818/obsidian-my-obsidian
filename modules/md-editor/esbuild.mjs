import esbuild from "esbuild";
import process from "process";
import builtins from "builtin-modules";
import { createRequire } from "node:module";
import { readFileSync, writeFileSync, rmSync } from "node:fs";
import path from "node:path";

const nodeRequire = createRequire(import.meta.url);

/**
 * wa-sqlite ships its compiled SQLite as a separate .wasm file. Bundling it
 * into main.js (as base64) is deliberate: a plugin has no reliable URL to
 * fetch it from, and a missing sidecar file would silently kill the SQLite
 * index. One file to deploy, nothing to fetch at runtime.
 */
const waSqliteDir = path.dirname(nodeRequire.resolve('wa-sqlite/package.json'));
const WA_SQLITE_WASM_B64 = readFileSync(path.join(waSqliteDir, 'dist', 'wa-sqlite.wasm')).toString('base64');

/**
 * vscode-oniguruma ships its Oniguruma regex engine as a separate .wasm file
 * (TextMate grammar engine for the extension market's syntax highlighting).
 * Same rationale as wa-sqlite above: bundle it as base64 — one deploy file,
 * nothing to fetch at runtime.
 */
const onigDir = path.dirname(nodeRequire.resolve('vscode-oniguruma/package.json'));
const ONIG_WASM_B64 = readFileSync(path.join(onigDir, 'release', 'onig.wasm')).toString('base64');

/**
 * Monaco (开源 VS Code 编辑器内核) 的 web worker:
 * 编辑器基础服务 + TS/JSON/CSS/HTML 语言服务。与 main.js 分文件部署到
 * 插件目录 monaco-workers/ 下,运行时经 adapter.getResourcePath 拿 app:// URL,
 * 再用 blob 包装 importScripts(Obsidian 内嵌 Monaco 的成熟做法)。
 */
const MONACO_WORKER_ENTRIES = [
  'monaco-editor/esm/vs/editor/editor.worker.js',
  'monaco-editor/esm/vs/language/typescript/ts.worker.js',
  'monaco-editor/esm/vs/language/json/json.worker.js',
  'monaco-editor/esm/vs/language/css/css.worker.js',
  'monaco-editor/esm/vs/language/html/html.worker.js',
];

async function buildMonacoWorkers() {
  await esbuild.build({
    entryPoints: MONACO_WORKER_ENTRIES.map((w) => ({
      in: nodeRequire.resolve(w),
      out: w.split('/').pop().replace(/\.js$/, ''),
    })),
    outdir: 'monaco-workers',
    bundle: true,
    format: 'iife',
    target: 'es2020',
    minify: prod,
    logLevel: 'warning',
  });
}

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === "production";

/**
 * `cm-bundle:` imports get their OWN bundled CodeMirror copy (used only by the
 * code-block editor). Everything reachable from such an import — including
 * @codemirror/* and @lezer/* pulled in transitively by e.g. lang-markdown — is
 * bundled into the same copy so facets/tags stay a single instance. Without
 * this, the transitive imports would fall through to the `external` list and
 * split the bundled copy across Obsidian's CM instance (broken highlighting).
 *
 * Resolution runs through a dedicated namespace because the external list is
 * matched on the raw specifier: inside the namespace we intercept every
 * @codemirror/@lezer import ourselves before externals apply.
 */
const cmBundlePlugin = {
  name: "cm-bundle",
  setup(build) {
    const CM_RE = /^cm-bundle:(.+)$/;
    const EXTERNAL_CM_RE = /^@(codemirror|lezer)\//;
    build.onResolve({ filter: /./ }, (args) => {
      const m = CM_RE.exec(args.path);
      const spec = m ? m[1] : null;
      // Transitive @codemirror/@lezer imports made from inside the bundled
      // copy stay bundled (one instance); from normal modules they fall
      // through to the global external list (Obsidian's shared CM).
      const isNested = args.namespace === "cm-bundle" && EXTERNAL_CM_RE.test(args.path);
      if (!spec && !isNested) return null;
      // Resolve bare specifiers with Node (build.resolve() applies the
      // external list, which is exactly what we must avoid here).
      return { path: nodeRequire.resolve(spec ?? args.path), namespace: "cm-bundle" };
    });
    // Modules in a custom namespace need an explicit loader.
    build.onLoad({ filter: /./, namespace: "cm-bundle" }, (args) => ({
      contents: readFileSync(args.path, "utf8"),
      loader: path.extname(args.path) === ".ts" ? "ts" : "js",
      resolveDir: path.dirname(args.path),
    }));
  },
};

const context = await esbuild.context({
  banner: { js: banner },
  entryPoints: ["src/main.ts"],
  bundle: true,
  // @codemirror/* and @lezer/* — EXTERNAL (official plugin convention):
  // Obsidian's loader provides the app's own CM6 instance, so our outline
  // editor shares ONE CodeMirror with the native editor and with community
  // plugins — which is what lets third-party registerEditorExtension bundles
  // (latex-suite live math preview, …) run in the outline editor.
  //
  // Exception: @codemirror/lang-markdown (and its @lezer/markdown parser) is
  // NOT among the modules Obsidian's loader provides — it is bundled here.
  // Its @codemirror/* and @lezer/common|highlight|lr imports still resolve to
  // the shared instance, so no duplicate state/view instances exist.
  external: [
    "obsidian",
    "electron",
    "@codemirror/state",
    "@codemirror/view",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/autocomplete",
    "@codemirror/search",
    "@codemirror/lint",
    "@codemirror/collab",
    "@lezer/common",
    "@lezer/highlight",
    "@lezer/lr",
    ...builtins,
  ],
  plugins: [cmBundlePlugin],
  // Monaco 的 ESM 会拉入 codicon 字体与布局 CSS:字体内联(dataurl),
  // CSS 由 esbuild 产出 main.css,构建后改名为 monaco.css(运行时注入)。
  loader: {
    '.ttf': 'dataurl',
    '.woff': 'dataurl',
    '.woff2': 'dataurl',
    '.png': 'dataurl',
    '.svg': 'dataurl',
    '.gif': 'dataurl',
  },
  define: {
    // wa-sqlite's Emscripten glue reads `import.meta.url` to locate its wasm.
    // In the CJS bundle that is `{}`, which makes its `q.indexOf("blob:")`
    // throw before it ever looks at `wasmBinary`. Empty string == "no script
    // dir", which is exactly what we want (we always pass `wasmBinary`).
    'import.meta.url': '""',
    // The compiled SQLite, embedded (see above).
    __WA_SQLITE_WASM_B64__: JSON.stringify(WA_SQLITE_WASM_B64),
    // The Oniguruma regex engine for the TextMate engine, embedded (see above).
    __ONIG_WASM_B64__: JSON.stringify(ONIG_WASM_B64),
  },
  format: "cjs",
  target: "es2020",
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  outfile: "main.js",
  minify: prod,
});

if (prod) {
  await buildMonacoWorkers();
  await context.rebuild();
  // esbuild 把从 JS 拉入的 CSS 写到与 outfile 同名的 main.css;改成 monaco.css
  // 交给运行时注入(不与插件自有的 styles.css 混写)。
  try {
    const css = readFileSync('main.css', 'utf8');
    writeFileSync('monaco.css', css);
    rmSync('main.css');
  } catch { /* 本次构建未产出 CSS 则跳过 */ }
  process.exit(0);
} else {
  await buildMonacoWorkers();
  await context.watch();
}
